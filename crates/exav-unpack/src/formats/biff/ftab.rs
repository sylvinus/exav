/// The built-in function of id `id` ([MS-XLS] 2.5.198.17 and the Excel 4.0
/// macro functions): its name, and its argument count when the id (a
/// `ptgFunc`) fixes it, else -1.
pub fn function(id: u16) -> Option<(&'static str, i8)> {
    FUNCTIONS
        .binary_search_by_key(&id, |e| e.0)
        .ok()
        .map(|k| (FUNCTIONS[k].1, FUNCTIONS[k].2))
}

/// The name of the function of a `ptgFunc` or `ptgFuncVar` token. A command
/// equivalent (an Excel 4.0 macro command) has the 0x8000 bit; it is looked up
/// as it is, and then with the bit the other way.
pub fn function_name(id: u16) -> Option<&'static str> {
    function(id).or_else(|| function(id ^ 0x8000)).map(|f| f.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_by_id_for_the_search() {
        assert!(FUNCTIONS.array_windows().all(|[a, b]| a.0 < b.0));
    }

    #[test]
    fn macro_functions_are_found_by_either_form_of_the_id() {
        assert_eq!(function_name(110), Some("EXEC"));
        assert_eq!(function_name(150), Some("CALL"));
        assert_eq!(function_name(32886), Some("ALERT"));
        // A command equivalent the table does not list takes the name of the
        // function without the bit.
        assert_eq!(function(32786), None);
        assert_eq!(function_name(32786), Some("ATAN"));
        assert_eq!(function(4), Some(("SUM", -1)));
        assert_eq!(function(2), Some(("ISNA", 1)));
        assert_eq!(function(0x7777), None);
    }
}
