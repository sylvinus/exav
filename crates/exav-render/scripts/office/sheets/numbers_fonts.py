#!/usr/bin/env python3
"""Writes src/formats/office/sheets/numbers/fonts.rs: the PostScript names of
macOS fonts whose family the rule in style::family (split at '-', drop an MT
or PSMT suffix, a space before each capital that follows a lower-case letter)
gets wrong, from numbers-parser's src/numbers_parser/generated/fontmap.py
(MIT, Jon Connell).

usage, from crates/exav-render:
python3 -I scripts/office/sheets/numbers_fonts.py fontmap.py > src/formats/office/sheets/numbers/fonts.rs
"""
import ast
import sys

text = open(sys.argv[1]).read()
fonts = ast.literal_eval(text[text.index("{"):])


def rule(ps):
    base = ps.split("-", 1)[0]
    for suffix in ("PSMT", "MT"):
        if base.endswith(suffix):
            base = base[: -len(suffix)]
            break
    out = ""
    prev_lower = False
    for c in base:
        if c.isupper() and prev_lower:
            out += " "
        prev_lower = c.islower()
        out += c
    return out


rows = sorted((ps, v["family"]) for ps, v in fonts.items() if rule(ps) != v["family"])
print("// Generated by scripts/office/sheets/numbers_fonts.py from numbers-parser's")
print("// fontmap.py (MIT, Jon Connell). Do not edit.")
print()
print("/// (PostScript name, family), by name.")
print("#[rustfmt::skip]")
print("pub(crate) const FAMILIES: &[(&str, &str)] = &[")
for ps, fam in rows:
    print(f'    ({ps!r}, {fam!r}),'.replace("'", '"'))
print("];")
