#!/usr/bin/env python3
"""Writes src/formats/office/sheets/xls/ftab.rs, the table of Excel's built-in
functions by their BIFF index, from scripts/office/sheets/ftab.json: rows of
[index, name, fixed argument count or -1], with the names of [MS-XLS]
2.5.198.17 Ftab and the argument counts of OpenOffice.org's Excel file format
documentation, 3.11.

usage, from crates/exav-render:
python3 -I scripts/office/sheets/ftab.py scripts/office/sheets/ftab.json > src/formats/office/sheets/xls/ftab.rs
"""
import json
import sys

rows = sorted(json.load(open(sys.argv[1])), key=lambda r: r[0])
print("// Generated by scripts/office/sheets/ftab.py from ftab.json. Do not edit.")
print()
print("/// (BIFF function index, name, fixed argument count or -1), by index.")
print("#[rustfmt::skip]")
print("pub(crate) const FTAB: &[(u16, &str, i8)] = &[")
for i, name, n in rows:
    print(f'    ({i}, "{name}", {n}),')
print("];")
