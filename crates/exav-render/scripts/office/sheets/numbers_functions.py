#!/usr/bin/env python3
"""Writes src/formats/office/sheets/numbers/functions.rs, Numbers' function
indexes (the AST_function_node_index of TSCE formula nodes) to their names,
from numbers-parser's src/numbers_parser/generated/functionmap.py (MIT, Jon
Connell), which maps them from the iWork applications.

usage, from crates/exav-render:
python3 -I scripts/office/sheets/numbers_functions.py functionmap.py > src/formats/office/sheets/numbers/functions.rs
"""
import re
import sys

text = open(sys.argv[1]).read()
rows = sorted((int(k), v) for k, v in re.findall(r'^\s*(\d+):\s*"([A-Z0-9.]+)"', text, re.M))
print("// Generated by scripts/office/sheets/numbers_functions.py from numbers-parser's")
print("// functionmap.py (MIT, Jon Connell). Do not edit.")
print()
print("/// (function index, name), by index.")
print("#[rustfmt::skip]")
print("pub(crate) const FUNCTIONS: &[(u32, &str)] = &[")
for k, v in rows:
    print(f'    ({k}, "{v}"),')
print("];")
