#!/usr/bin/env python3
"""Writes src/formats/office/common/codepage_tables.rs: the single-byte DOS and
Mac code pages that encoding_rs does not have, as tables of 256 UTF-16 code
units, from Python's own codecs. Undefined bytes map to U+FFFD.

usage, from crates/exav-render:
python3 -I scripts/office/common/codepages.py > src/formats/office/common/codepage_tables.rs
"""

PAGES = [
    (437, "cp437"),
    (720, "cp720"),
    (737, "cp737"),
    (775, "cp775"),
    (850, "cp850"),
    (852, "cp852"),
    (855, "cp855"),
    (857, "cp857"),
    (858, "cp858"),
    (860, "cp860"),
    (861, "cp861"),
    (862, "cp862"),
    (863, "cp863"),
    (864, "cp864"),
    (865, "cp865"),
    (869, "cp869"),
    (10006, "mac_greek"),
    (10029, "mac_latin2"),
    (10079, "mac_iceland"),
    (10081, "mac_turkish"),
]


def table(codec):
    out = []
    for b in range(256):
        try:
            s = bytes([b]).decode(codec)
        except UnicodeDecodeError:
            s = "�"
        cp = ord(s) if len(s) == 1 else 0xFFFD
        if cp > 0xFFFF:
            cp = 0xFFFD
        out.append(cp)
    return out


print("// Generated by scripts/office/common/codepages.py from Python's codecs. Do not edit.")
print()
print("/// (code page, its 256 characters).")
print("#[rustfmt::skip]")
print("pub(crate) static TABLES: &[(u16, [u16; 256])] = &[")
for cp, codec in PAGES:
    t = table(codec)
    print(f"    // {codec}")
    print(f"    ({cp}, [")
    for i in range(0, 256, 16):
        print("        " + ", ".join(f"0x{x:04X}" for x in t[i:i + 16]) + ",")
    print("    ]),")
print("];")
