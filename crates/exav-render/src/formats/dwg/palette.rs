//! The AutoCAD Colour Index, in both of its published forms.
//!
//! An indexed colour does not have one RGB value. AutoCAD resolves it against
//! the drawing area's background so the result stays legible, and the two
//! tables below differ on 223 of their 255 entries. `Light` is the classic
//! table that older references publish and that matches a plot on white paper;
//! `Dark` is the table AutoCAD 2020 uses against its default dark model-space
//! background, RGB(33, 40, 48), the same colour this viewer offers as its
//! `dark` preset.
//!
//! Index 0 is ByBlock and 256 is ByLayer; neither is a colour, and both are
//! resolved before a lookup reaches here. Slot 0 exists only to keep the index
//! equal to the array position.
//!
//! Sources: the classic table as compiled in `acadrgb.txt` and republished at
//! <https://gohtx.com/acadcolors.php>; the dark table cross-checked against
//! ezdxf's `DXF_DEFAULT_COLORS` (MIT), whose own comment records which
//! background it corresponds to. Colour values are measurements, not authorship.

/// Which background the palette is being read against.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Palette {
    /// A light background, and what a drawing plots as on paper.
    #[default]
    Light,
    /// AutoCAD's dark model space.
    Dark,
}

impl Palette {
    /// Pick the table that matches a background colour.
    pub fn for_background(r: u8, g: u8, b: u8) -> Palette {
        // Rec. 709 luma, the same test the shader uses for colour 7.
        let luma = 0.2126 * r as f64 + 0.7152 * g as f64 + 0.0722 * b as f64;
        if luma > 127.5 {
            Palette::Light
        } else {
            Palette::Dark
        }
    }

    /// RGB for an index in 1..=255.
    pub fn rgb(&self, index: u8) -> (u8, u8, u8) {
        let table = match self {
            Palette::Light => &LIGHT,
            Palette::Dark => &DARK,
        };
        let c = table[index as usize];
        (c[0], c[1], c[2])
    }
}

