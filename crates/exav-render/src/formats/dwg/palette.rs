#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_primaries_agree_between_the_two_tables() {
        // 1-7 are the colours every implementation gets right; a difference
        // there would mean one of the tables was transcribed wrongly.
        for i in 1..=7u8 {
            assert_eq!(Palette::Light.rgb(i), Palette::Dark.rgb(i), "index {i}");
        }
        assert_eq!(Palette::Light.rgb(1), (255, 0, 0));
        assert_eq!(Palette::Light.rgb(5), (0, 0, 255));
        assert_eq!(Palette::Light.rgb(7), (255, 255, 255));
    }

    #[test]
    fn the_greys_differ_by_background() {
        // The entries that made this worth doing. On white, 8 is nearly black
        // so it reads; against dark model space it lightens to a mid grey.
        assert_eq!(Palette::Light.rgb(8), (65, 65, 65));
        assert_eq!(Palette::Dark.rgb(8), (128, 128, 128));
        assert_eq!(Palette::Light.rgb(9), (128, 128, 128));
        assert_eq!(Palette::Dark.rgb(9), (192, 192, 192));

        // The greyscale tail, which site plans use heavily.
        assert_eq!(Palette::Light.rgb(252), (105, 105, 105));
        assert_eq!(Palette::Dark.rgb(252), (102, 102, 102));
        assert_eq!(Palette::Light.rgb(254), (190, 190, 190));
        assert_eq!(Palette::Dark.rgb(254), (204, 204, 204));
    }

    #[test]
    fn the_light_table_is_the_darker_one_where_it_matters() {
        // The whole point of two tables: an index has to stay legible, so the
        // light background gets the darker ink. Check it holds across the
        // greyscale run rather than at one entry.
        let luma =
            |(r, g, b): (u8, u8, u8)| 0.2126 * r as f64 + 0.7152 * g as f64 + 0.0722 * b as f64;
        for i in [8u8, 9, 251, 253, 254] {
            assert!(
                luma(Palette::Light.rgb(i)) < luma(Palette::Dark.rgb(i)),
                "index {i}: light {:?} is not darker than dark {:?}",
                Palette::Light.rgb(i),
                Palette::Dark.rgb(i)
            );
        }
    }

    #[test]
    fn a_background_picks_the_matching_table() {
        assert_eq!(Palette::for_background(255, 255, 255), Palette::Light);
        // AutoCAD's own dark model space.
        assert_eq!(Palette::for_background(33, 40, 48), Palette::Dark);
        assert_eq!(Palette::for_background(0, 0, 0), Palette::Dark);
    }

    #[test]
    fn every_index_resolves() {
        for i in 1..=255u8 {
            let (r, g, b) = Palette::Light.rgb(i);
            let _ = (r, g, b);
            let (r, g, b) = Palette::Dark.rgb(i);
            let _ = (r, g, b);
        }
    }
}
