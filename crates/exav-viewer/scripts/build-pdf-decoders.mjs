// Writes pdf.js's two image decoder fallbacks, openjpeg_nowasm_fallback.js and
// jbig2_nowasm_fallback.js, each one file: the module's wasm-bindgen glue
// (`--target no-modules`, wrapped so that each call makes a fresh instance's
// state), the module itself in base64, and scripts/pdf-decoder.template.js.
// Also writes pdf_decoders.js, whose PDF_DECODERS (a hash of both) names the
// directory they are published in, so that it can be served immutable.
//
// Usage: node scripts/build-pdf-decoders.mjs <wasm-bindgen out dir> <out dir>
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const [from, to] = process.argv.slice(2);
if (!from || !to) {
  console.error("usage: build-pdf-decoders.mjs <wasm-bindgen out dir> <out dir>");
  process.exit(2);
}
const template = fs.readFileSync(path.join(here, "pdf-decoder.template.js"), "utf8");

const DECODERS = [
  { module: "exav_viewer_pdf_jpx", file: "openjpeg_nowasm_fallback.js", replaces: "OpenJPEG" },
  { module: "exav_viewer_pdf_jbig2", file: "jbig2_nowasm_fallback.js", replaces: "PDFium's JBIG2 and CCITT decoders" },
];

const hash = createHash("sha256");
for (const d of DECODERS) {
  const glue = fs.readFileSync(path.join(from, `${d.module}.js`), "utf8");
  if (!glue.startsWith("let wasm_bindgen = ")) throw new Error(`${d.module}.js is not wasm-bindgen's no-modules glue`);
  const wasm = fs.readFileSync(path.join(from, `${d.module}_bg.wasm`));
  const source = [
    `// @exav/viewer: pdf.js's decoder fallback, in place of ${d.replaces}.`,
    `// Generated by scripts/build-pdf-decoders.mjs from exav-render (MIT); see`,
    `// the package's NOTICE. Module: ${d.module}_bg.wasm.`,
    `const WASM = "${wasm.toString("base64")}";`,
    "",
    "function bindings() {",
    glue.trimEnd(),
    "  return wasm_bindgen;",
    "}",
    "",
    template,
  ].join("\n");
  fs.writeFileSync(path.join(to, d.file), source);
  hash.update(source);
  console.log(`${d.file}: ${wasm.length} bytes of wasm, ${source.length} of JavaScript`);
}
const id = hash.digest("hex").slice(0, 10);
fs.writeFileSync(
  path.join(to, "pdf_decoders.js"),
  `// Generated by scripts/build-pdf-decoders.mjs: names the directory of pdf.js's\n// wasm assets and this package's decoders (see ts/pdf/assets.ts).\nexport const PDF_DECODERS = "${id}";\n`,
);
fs.writeFileSync(path.join(to, "pdf_decoders.d.ts"), "export declare const PDF_DECODERS: string;\n");
