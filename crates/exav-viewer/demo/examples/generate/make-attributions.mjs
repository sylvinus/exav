#!/usr/bin/env node
// Writes the credits of the demo's examples from examples.json:
//
//   - ../NOTICE.md, the list with every fact of the manifest, and
//   - www/src/content/docs/viewer/examples.md, the page of the site.
//
//     node generate/make-attributions.mjs            # write both
//     node generate/make-attributions.mjs --check    # fail if either is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const repo = path.join(root, "..", "..", "..", "..");
const check = process.argv.includes("--check");

const { examples } = JSON.parse(fs.readFileSync(path.join(root, "examples.json"), "utf8"));
const showcase = fs.readFileSync(path.join(root, "..", "src", "showcase.ts"), "utf8");
const groups = [...showcase.matchAll(/^\s+(?:"([\w-]+)"|(\w+)): \{ en: "([^"]+)"/gm)].map((m) => ({ id: m[1] ?? m[2], label: m[3] }));

const kb = (n) => (n < 1024 ? `${n} B` : n < 1024 * 1024 ? `${(n / 1024).toFixed(n < 10240 ? 1 : 0)} KB` : `${(n / 1024 / 1024).toFixed(1)} MB`);
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const host = (u) => new URL(u).hostname.replace(/^www\./, "");
const SPDX_URL = (id) => {
  if (id === "CC0-1.0") return "https://creativecommons.org/publicdomain/zero/1.0/";
  const m = /^CC-BY(-SA)?-(\d\.\d)$/.exec(id);
  if (m) return `https://creativecommons.org/licenses/by${m[1] ? "-sa" : ""}/${m[2]}/`;
  if (/^(MIT|BSD-2-Clause|BSD-3-Clause|Apache-2\.0)$/.test(id)) return `https://spdx.org/licenses/${id}.html`;
  return null;
};
const origin = (e) => {
  if (e.generated) return `generated by \`${e.generated.script}\`${e.generated.args.length ? ` ${e.generated.args.join(" ")}` : ""}${e.generated.tools ? ` (with ${e.generated.tools.join(", ")})` : ""}`;
  if (e.fixture) return `a fixture of this repository, \`${e.fixture}\``;
  return `downloaded from ${e.fetched}`;
};

const ordered = [...groups.map((g) => g.id), ...new Set(examples.map((e) => e.group))].filter((g, i, a) => a.indexOf(g) === i);
const byGroup = (id) => examples.filter((e) => e.group === id);
const label = (id) => groups.find((g) => g.id === id)?.label ?? id;

const total = (list) => list.reduce((n, e) => n + e.bytes, 0);
const committed = examples.filter((e) => e.committed);

// ----------------------------------------------------------------- NOTICE.md
const notice = [
  "# Notices of the example files",
  "",
  "The demo of `@exav/viewer` lists the files of this directory's `examples.json`. Each has a free licence",
  "that was read at the page named under \"Evidence\", or is made by a script of this repository and",
  "given to the public domain (CC0-1.0). This file is written by `generate/make-attributions.mjs`; do not edit it.",
  "",
  `${examples.length} files: ${committed.length} are committed under \`files/\` (${kb(total(committed))}); ${examples.length - committed.length} are downloaded by \`npm run demo:examples\` (${kb(total(examples.filter((e) => !e.committed)))}).`,
  "",
  "To rebuild: run the scripts of `generate/` (each lists what it needs; `python3 -I generate/make-images.py`, `make-cad.py`,",
  "`make-models.py`, `make-ifc.py`, `make-text.py`, `make-archives.py`, `make-media.py`, `make-pdf.py`, `make-office.py`), then",
  "`node generate/make-manifest.mjs` and `node generate/make-attributions.mjs`. `node check.mjs` checks the manifest and the",
  "files, `node verify-open.mjs` opens every example with the viewer's own engines, and `node generate/verify-evidence.mjs`",
  "reads the licence pages again. `catalog.json` is where each example is described by hand.",
  "",
  "Where the pictures made here hold text, it is set in Aileron, the font Pillow bundles, which its author gives to the",
  "public domain (CC0-1.0, \"No Rights Reserved\": https://dotcolon.net/font/aileron/). Drawings name their fonts and",
  "embed none; documents that embed fonts embed the Liberation fonts (SIL OFL 1.1, which lets documents embed them).",
  "",
];
for (const id of ordered) {
  const list = byGroup(id);
  if (!list.length) continue;
  notice.push(`## ${label(id)}`, "");
  for (const e of list) {
    notice.push(`### ${e.file}`, "");
    notice.push(`- What: ${e.title} (${e.family}, ${kb(e.bytes)})`);
    if (e.features) notice.push(`- Shows: ${e.features}`);
    notice.push(`- Author: ${e.author}`);
    notice.push(`- Source: ${e.source}`);
    notice.push(`- Licence: ${e.licence}`);
    notice.push(`- Evidence: ${e.evidence}`);
    notice.push(`- Words read there: "${e.evidence_quote}"`);
    if (e.attribution) notice.push(`- Attribution: ${e.attribution}`);
    if (e.derived) notice.push(`- Changes: ${e.derived}`);
    notice.push(`- Origin: ${origin(e)}`);
    notice.push(`- SHA-256: ${e.sha256}`, "");
  }
}

// ------------------------------------------------------------------ the page
const page = [
  "---",
  "title: Example files",
  "description: \"The files of the @exav/viewer demo: what each is, who made it, where it comes from and its licence.\"",
  "---",
  "",
  "<!-- Written by crates/exav-viewer/demo/examples/generate/make-attributions.mjs from examples.json. Do not edit. -->",
  "",
  `The [demo](/viewer/demo/) lists ${examples.length} example files, one or more for each format the viewer reads. Each is public domain, CC0,`,
  "CC-BY, or an MIT, BSD or Apache test file, and its licence was read at the source page named below.",
  "Most are made for the demo by scripts of the repository and given to the public domain (CC0-1.0); the others",
  "are credited here and in the demo's licence notice. A file is downloaded only when it is opened.",
  "",
  "The facts are in [`examples.json`](https://github.com/sylvinus/exav/blob/main/crates/exav-viewer/demo/examples/examples.json)",
  "and [`NOTICE.md`](https://github.com/sylvinus/exav/blob/main/crates/exav-viewer/demo/examples/NOTICE.md): the page",
  "that states each licence, the words read there, the SHA-256 of the file, and how it was made or fetched.",
  "",
];
for (const id of ordered) {
  const list = byGroup(id);
  if (!list.length) continue;
  page.push(`## ${label(id)}`, "", "| File | Format | Size | Author | Source | Licence |", "| --- | --- | ---: | --- | --- | --- |");
  for (const e of list) {
    const lic = SPDX_URL(e.licence) ? `[${cell(e.licence)}](${SPDX_URL(e.licence)})` : cell(e.licence);
    const what = e.generated ? "made for the demo" : `[${host(e.source)}](${e.source})`;
    page.push(`| \`${e.file}\` | ${cell(e.family)} | ${kb(e.bytes)} | ${cell(e.author)} | ${what} | ${lic} |`);
  }
  page.push("");
}
const credited = examples.filter((e) => e.attribution);
if (credited.length) {
  page.push("## Attributions", "", "The lines the licences ask to keep:", "");
  for (const e of credited) page.push(`- \`${e.file}\`: ${e.attribution}`);
  page.push("");
}

const targets = [
  [path.join(root, "NOTICE.md"), `${notice.join("\n")}\n`],
  [path.join(repo, "www", "src", "content", "docs", "viewer", "examples.md"), `${page.join("\n")}\n`],
];
let stale = false;
for (const [file, text] of targets) {
  const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (check) {
    if (now !== text) {
      console.error(`${path.relative(repo, file)} is out of date: run node generate/make-attributions.mjs`);
      stale = true;
    }
  } else if (now !== text) {
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(repo, file)}`);
  }
}
if (stale) process.exit(1);
